test('a failed JavaScript download reveals the usable fallback', async ({ page }) => {
  await page.clock.install()
  await page.route('**/assets/*.js', (route) => route.abort())
  await page.goto('/', { waitUntil: 'domcontentloaded' })
  await page.clock.fastForward(11000)
  await expect(page.locator('#seo-root')).toBeVisible()
  await expect(page.locator('#boot-root')).toBeHidden()
  await expect(page.locator('#seo-root header a').first()).toBeVisible()
})

