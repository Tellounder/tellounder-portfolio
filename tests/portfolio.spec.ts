test('vinyl keeps rotating and its pause control still works', async ({ page }) => {
  test.setTimeout(60000)
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.goto('/proyectos/metalmente-arte')
  const label = page.locator('.record-label')
  await expect(label).toBeVisible()
  const transform = await label.evaluate((element) => getComputedStyle(element).transform)
  await expect.poll(() => label.evaluate((element) => getComputedStyle(element).transform)).not.toBe(transform)
  await page.getByRole('button', { name: 'Pausar tocadiscos' }).click()
  await expect.poll(() => label.evaluate((element) => getComputedStyle(element).animationPlayState)).toBe('paused')
  await page.getByRole('button', { name: 'Reproducir tocadiscos' }).click()
  await expect.poll(() => label.evaluate((element) => getComputedStyle(element).animationPlayState)).toBe('running')
})
