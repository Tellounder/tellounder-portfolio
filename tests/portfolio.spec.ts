import { test, expect } from '@playwright/test'

test('first paint shows the brand before JS, then enters once with optional audio', async ({ page }, testInfo) => {
  let release!: () => void
  const hold = new Promise<void>((resolve) => { release = resolve })
  await page.route('**/assets/*.js', async (route) => { await hold; await route.continue() })
  await page.goto('/', { waitUntil: 'commit' })
  await expect(page.locator('#boot-enter')).toBeVisible()
  await expect(page.locator('#seo-root')).toBeHidden()
  await expect(page.locator('#app-root')).toBeEmpty()
  await expect(page.locator('#boot-audio')).not.toBeChecked()
  await page.screenshot({ path: testInfo.outputPath('boot-desktop.png') })
  await page.locator('#boot-audio').check()
  await page.locator('#boot-enter').click()
  await expect(page.locator('#boot-enter')).toHaveText('Abriendo experiencias…')
  release()
  await expect(page.locator('html')).toHaveClass(/app-ready/)
  await expect(page.locator('.top-tools button').last()).toHaveText('AUDIO ON')
  await expect(page.locator('#boot-root')).toBeHidden()
  await page.reload()
  await expect(page.locator('html')).toHaveClass(/boot-resuming/)
  await expect(page.locator('html')).toHaveClass(/app-ready/)
  await expect(page.locator('#boot-root')).toBeHidden()
})

