    await art.scrollIntoViewIfNeeded()
    await expect.poll(() => art.evaluate((img: HTMLImageElement) => img.naturalWidth)).toBeGreaterThan(0)
    sources.add((await art.getAttribute('src'))!)
    const src = (await art.getAttribute('src'))!
